"""Не давать экрану погаснуть, пока идёт сборка кампании.

Заблокированный экран останавливает прогон. Windows уходит на защищённый
рабочий стол, браузер перестаёт получать время, и креатив, который
загружается за 74 секунды, грузился 42 минуты, после чего прогон сдался.
Это та же беда, что и свёрнутое окно, только сильнее: человек видит
падение без видимой причины.

Мы просим систему не гасить экран и не засыпать, пока работа идёт, и
отпускаем просьбу, как только она кончилась. Ровно так делает
проигрыватель видео на время фильма. Это не изменение настроек
безопасности машины и не попытка им стать: блокировку, которую человек
включил сам (Win+L) или которую навязывает политика домена, отменить
нельзя и не нужно — это не наше дело.

Просьба живёт на **потоке**, а не на процессе: `SetThreadExecutionState`
так устроена. Работа публикации и так идёт в своём потоке, и это ровно то,
что нужно — соседние потоки дешборда ничего не меняют.
"""
from __future__ import annotations

import contextlib
import logging
import sys
from typing import Iterator

log = logging.getLogger(__name__)

# Значения из WinBase.h.
ES_CONTINUOUS = 0x80000000        # состояние держится, пока не сменим
ES_SYSTEM_REQUIRED = 0x00000001   # машина не засыпает
ES_DISPLAY_REQUIRED = 0x00000002  # экран не гаснет

_BUSY = ES_CONTINUOUS | ES_SYSTEM_REQUIRED | ES_DISPLAY_REQUIRED
_IDLE = ES_CONTINUOUS              # снять просьбу, вернув обычное поведение


def _kernel32():
    """`kernel32` там, где он есть. На других системах — None, и тишина.

    Дешборд разрабатывают и гоняют тесты не только на Windows, а падать в
    публикации из-за отсутствующей библиотеки — цена несоразмерная тому,
    что мы просим.
    """
    if not sys.platform.startswith("win"):
        return None
    try:
        import ctypes

        return ctypes.windll.kernel32
    except Exception:
        return None


def _set(flags: int) -> bool:
    api = _kernel32()
    if api is None:
        return False
    try:
        # Возвращает прежнее состояние или 0 при отказе.
        return bool(api.SetThreadExecutionState(flags))
    except Exception:
        return False


@contextlib.contextmanager
def keep_display_awake(reason: str = "") -> Iterator[bool]:
    """Пока тело выполняется, экран не гаснет и машина не засыпает.

    Отдаёт True, если просьба принята. Ложь — не повод не работать: на
    машине без Windows или при отказе API прогон идёт как шёл, просто без
    этой страховки.

    Снимается в `finally`: прогон может кончиться и падением, и отменой, а
    оставленная просьба пережила бы работу и держала бы экран включённым
    неизвестно сколько.
    """
    held = _set(_BUSY)
    if held:
        log.info("Экран удерживается включённым на время работы%s",
                 f" ({reason})" if reason else "")
    else:
        log.debug("Удержание экрана недоступно — работаем без него")
    try:
        yield held
    finally:
        if held:
            _set(_IDLE)
            log.debug("Удержание экрана снято")
